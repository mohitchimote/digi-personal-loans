/**
 * Generates seed-reference.sql: reference data pulled from public sources (too large or too
 * volatile to hand-write). Run AFTER seed-masters.sql (it needs the master types and countries):
 *
 *   npx tsx scripts/seed-reference.ts > seed-reference.sql          (downloads on first run, then caches)
 *   npx wrangler d1 execute digibank --local  --file=./seed-reference.sql
 *   npx wrangler d1 execute digibank --remote --file=./seed-reference.sql   (~165k rows: mind D1 write limits)
 *
 * Sources
 *  - Nationalities: demonyms from Wikidata (property P1549), English and Hebrew, one per ISO country.
 *  - States / provinces and cities: github.com/dr5hn/countries-states-cities-database, pinned to a
 *    commit so a re-run is reproducible. Hebrew state names come from Wikidata labels; the dataset has
 *    no Hebrew city names, so a city's Hebrew name falls back to its English one (Israel's cities get
 *    Hebrew labels from Wikidata where they match).
 *  - Banks and bank branches: the Bank of Israel physical-branch directory on data.gov.il, which
 *    publishes matching Hebrew and English versions.
 *
 * Idempotent: INSERT OR IGNORE on the unique keys, and name refreshes only touch rows an admin has
 * never edited (updated_at IS NULL). Progress and fallback counts go to stderr.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ISO_COUNTRIES } from "./lib/iso-countries";

const CACHE_DIR = fileURLToPath(new URL("../.cache/", import.meta.url));
mkdirSync(CACHE_DIR, { recursive: true });
const log = (m: string) => process.stderr.write(m + "\n");
const q = (v: string) => `'${v.replace(/'/g, "''")}'`;
const now = new Date().toISOString();
const UA = "digibank-reference-data-seed/1.0 (local development data import)";

const DR5HN = "https://raw.githubusercontent.com/dr5hn/countries-states-cities-database/1ac7dcead105f60240e95b9919592ae531acf8ea/json";
const WIKIDATA = "https://query.wikidata.org/sparql";
const BOI_EN = "6f3bda2a-8cde-4b86-a1c8-2761862b1224"; // data.gov.il: physical bank branches, English
const BOI_HE = "2202bada-4baf-45f5-aa61-8c5bad9646d3"; // same, Hebrew

async function cached<T>(name: string, load: () => Promise<T>): Promise<T> {
  const file = CACHE_DIR + name;
  if (existsSync(file)) return JSON.parse(readFileSync(file, "utf8")) as T;
  const data = await load();
  writeFileSync(file, JSON.stringify(data));
  return data;
}
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function getJson(url: string): Promise<any> {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return res.json();
}

async function sparql(query: string): Promise<any[]> {
  for (let attempt = 1; attempt <= 3; attempt++) {
    const res = await fetch(WIKIDATA, {
      method: "POST",
      headers: { "User-Agent": UA, Accept: "application/sparql-results+json", "Content-Type": "application/x-www-form-urlencoded" },
      body: new URLSearchParams({ query }),
    });
    if (res.ok) {
      try { return (await res.json()).results.bindings; }
      catch { log(`  Wikidata returned a truncated/invalid response (likely a query timeout), retry ${attempt}/3`); }
    } else log(`  Wikidata HTTP ${res.status}, retry ${attempt}/3`);
    await sleep(3000 * attempt);
  }
  throw new Error("Wikidata query failed");
}

const out: string[] = ["-- Generated by scripts/seed-reference.ts - do not edit by hand. Idempotent.", ""];
const emit = (s: string) => out.push(s);

// Inserts rows whose parent is looked up by (parent type, parent code). Chunked so no statement nears
// D1's 100 KB limit. Rows with an unknown parent are skipped by the join (never inserted unparented).
type ChildRow = { code: string; en: string; he: string; parentCode: string; attrs?: Record<string, unknown>; active?: boolean };
function emitChildren(type: string, parentType: string, rows: ChildRow[]) {
  const CHUNK = 200;
  for (let i = 0; i < rows.length; i += CHUNK) {
    const values = rows.slice(i, i + CHUNK).map((r) =>
      `(${q(r.code)}, ${q(r.en)}, ${q(r.he)}, ${q(r.parentCode)}, ${q(JSON.stringify(r.attrs ?? {}))}, ${r.active === false ? 0 : 1})`).join(",\n  ");
    emit(
      `WITH v(code, en, he, parent, attrs, active) AS (VALUES\n  ${values})\n` +
      `INSERT OR IGNORE INTO master_items (type_code, code, name_en, name_he, parent_id, sort_order, active, attributes, created_at)\n` +
      `SELECT ${q(type)}, v.code, v.en, v.he, p.id, 0, v.active, v.attrs, ${q(now)} FROM v\n` +
      `JOIN master_items p ON p.type_code = ${q(parentType)} AND p.code = v.parent;`,
    );
  }
  emit("");
}

// ---------------------------------------------------------------------------------------------------
// 1. Nationalities (demonyms)
// ---------------------------------------------------------------------------------------------------
async function nationalities() {
  log("Nationalities: querying Wikidata demonyms ...");
  const rows = await cached("demonyms.json", () =>
    sparql('SELECT ?iso ?d WHERE { ?c wdt:P297 ?iso . ?c wdt:P1549 ?d . FILTER(LANG(?d)="he" || LANG(?d)="en") }'));
  const by = new Map<string, { en: string[]; he: string[] }>();
  for (const r of rows) {
    const e = by.get(r.iso.value) ?? { en: [], he: [] };
    (r.d["xml:lang"] === "he" ? e.he : e.en).push(r.d.value);
    by.set(r.iso.value, e);
  }
  // English: drop plurals ("Israelis" when "Israeli" exists), then the longest form ("British" over "Briton").
  const pickEn = (vals: string[]) => {
    const singular = vals.filter((v) => !(v.endsWith("s") && vals.includes(v.slice(0, -1))));
    return [...(singular.length ? singular : vals)].sort((a, b) => b.length - a.length)[0];
  };
  // Hebrew: masculine singular, i.e. drop feminine (ית, ייה) and plural (ים, ות) endings.
  const pickHe = (vals: string[]) => {
    const masc = vals.filter((v) => !/(ית|ייה|ים|ות)$/.test(v));
    return [...(masc.length ? masc : vals)].sort((a, b) => a.length - b.length)[0];
  };
  const MANUAL_HE: Record<string, string> = { PS: "פלסטיני" };
  let fbEn = 0, fbHe = 0;
  for (const [code, en, he] of ISO_COUNTRIES) {
    const d = by.get(code);
    let nEn = d?.en.length ? pickEn(d.en) : "";
    let nHe = MANUAL_HE[code] ?? (d?.he.length ? pickHe(d.he) : "");
    if (!nEn) { nEn = `Citizen of ${en}`; fbEn++; }
    if (!nHe) { nHe = `אזרח ${he}`; fbHe++; }
    emit(
      `INSERT INTO master_items (type_code, code, name_en, name_he, parent_id, sort_order, active, attributes, created_at) ` +
      `VALUES ('nationality', ${q(code)}, ${q(nEn)}, ${q(nHe)}, NULL, 0, 1, '{}', ${q(now)}) ` +
      `ON CONFLICT(type_code, code) DO UPDATE SET name_en = excluded.name_en, name_he = excluded.name_he WHERE master_items.updated_at IS NULL;`,
    );
  }
  // The old pick-list had an "Other" for people whose nationality isn't listed.
  emit(
    `INSERT OR IGNORE INTO master_items (type_code, code, name_en, name_he, parent_id, sort_order, active, attributes, created_at) ` +
    `VALUES ('nationality', 'OTHER', 'Other', 'אחר', NULL, 99999, 1, '{}', ${q(now)});`,
  );
  emit("");
  log(`  ${ISO_COUNTRIES.length} nationalities; fallback wording used for ${fbEn} English and ${fbHe} Hebrew entries`);
}

// ---------------------------------------------------------------------------------------------------
// 2. States / provinces and cities
// ---------------------------------------------------------------------------------------------------
interface DrState { id: string; name: string; country_code: string; iso3166_2: string | null; parent_id: string | null; wikiDataId: string | null }
const none = (v: unknown) => v === null || v === undefined || v === "None" || v === "";

async function geography() {
  log("States and cities: downloading dr5hn dataset (pinned commit) ...");
  const states: DrState[] = await cached("dr5hn-states.json", () => getJson(`${DR5HN}/states.json`));
  const tree: any[] = await cached("dr5hn-csc.json", () => getJson(`${DR5HN}/countries%2Bstates%2Bcities.json`));
  const known = new Set(ISO_COUNTRIES.map((c) => c[0]));

  // Top-level subdivisions become the "state" master; second-level ones (counties, districts) are
  // folded into their ancestor so their cities still hang off a state.
  const byId = new Map(states.map((s) => [String(s.id), s]));
  const rootOf = (s: DrState): DrState => {
    let cur = s; const seen = new Set<string>();
    while (!none(cur.parent_id) && byId.has(String(cur.parent_id)) && !seen.has(cur.id)) { seen.add(cur.id); cur = byId.get(String(cur.parent_id))!; }
    return cur;
  };
  const stateCode = new Map<string, string>(); // dr5hn id -> our code
  const used = new Set<string>();
  const stateRows: ChildRow[] = [];
  const roots = states.filter((s) => none(s.parent_id) && known.has(s.country_code));
  // Hebrew state names via Wikidata labels
  const qids = [...new Set(roots.map((s) => s.wikiDataId).filter((v): v is string => !none(v)))];
  log(`  ${roots.length} top-level subdivisions; fetching Hebrew labels for ${qids.length} Wikidata ids ...`);
  const heLabels = await cached<Record<string, string>>("state-he-labels.json", async () => {
    const m: Record<string, string> = {};
    for (let i = 0; i < qids.length; i += 250) {
      const batch = qids.slice(i, i + 250);
      const rows = await sparql(`SELECT ?q ?l WHERE { VALUES ?q { ${batch.map((x) => `wd:${x}`).join(" ")} } ?q rdfs:label ?l FILTER(LANG(?l)="he") }`);
      for (const r of rows) m[r.q.value.split("/").pop()!] = r.l.value;
      log(`    labels ${Math.min(i + 250, qids.length)}/${qids.length}`);
      await sleep(1200);
    }
    return m;
  });
  let heStates = 0;
  for (const s of roots) {
    let code = !none(s.iso3166_2) ? s.iso3166_2! : `${s.country_code}-S${s.id}`;
    if (used.has(code)) code = `${s.country_code}-S${s.id}`;
    used.add(code); stateCode.set(String(s.id), code);
    const he = !none(s.wikiDataId) ? heLabels[s.wikiDataId!] : undefined;
    if (he) heStates++;
    stateRows.push({ code, en: s.name, he: he ?? s.name, parentCode: s.country_code });
  }
  emitChildren("state", "country", stateRows);
  log(`  ${stateRows.length} states emitted (${heStates} with a Hebrew name; the rest show the English name in Hebrew)`);

  // Israel's cities: Hebrew labels from Wikidata, matched on the English label.
  // (Settlements are the Israeli items that carry a population figure: a light query that finishes
  // within Wikidata's time limit, unlike walking the whole "human settlement" class tree.)
  const ilHe = await cached<Record<string, string>>("il-city-he.json", async () => {
    log("  Israeli settlements: fetching Hebrew labels ...");
    const m: Record<string, string> = {};
    try {
      const rows = await sparql(
        'SELECT ?en ?he WHERE { ?c wdt:P17 wd:Q801 ; wdt:P1082 ?pop ; rdfs:label ?en ; rdfs:label ?he . FILTER(LANG(?en)="en" && LANG(?he)="he") }');
      for (const r of rows) m[r.en.value.toLowerCase()] = r.he.value;
    } catch (e) { log(`  (skipped: ${(e as Error).message}; Israeli cities will show English names in Hebrew)`); }
    return m;
  });

  const cityRows: ChildRow[] = [];
  let ilMatched = 0, ilTotal = 0;
  for (const country of tree) {
    if (!known.has(country.iso2)) continue;
    for (const st of country.states ?? []) {
      const info = byId.get(String(st.id));
      if (!info) continue;
      const parent = stateCode.get(String(rootOf(info).id));
      if (!parent) continue;
      for (const c of st.cities ?? []) {
        let he: string = c.name;
        if (country.iso2 === "IL") { ilTotal++; const h = ilHe[String(c.name).toLowerCase()]; if (h) { he = h; ilMatched++; } }
        cityRows.push({ code: `${country.iso2}-${c.id}`, en: c.name, he, parentCode: parent });
      }
    }
  }
  emitChildren("city", "state", cityRows);
  log(`  ${cityRows.length} cities emitted (Israel: ${ilMatched}/${ilTotal} with a Hebrew name)`);
}

// ---------------------------------------------------------------------------------------------------
// 3. Banks and bank branches (Bank of Israel)
// ---------------------------------------------------------------------------------------------------
async function banks() {
  log("Banks: downloading the Bank of Israel branch directory ...");
  const fetchAll = async (id: string) => (await getJson(`https://data.gov.il/api/3/action/datastore_search?resource_id=${id}&limit=5000`)).result.records as any[];
  const en = await cached("boi-en.json", () => fetchAll(BOI_EN));
  const he = await cached("boi-he.json", () => fetchAll(BOI_HE));
  const heById = new Map(he.map((r) => [r._id, r]));
  const clean = (v: unknown) => String(v ?? "").replace(/\s+/g, " ").trim();
  const title = (v: string) => v.toLowerCase().replace(/\b[a-z]/g, (m) => m.toUpperCase());
  const pad = (v: unknown, n: number) => String(v).padStart(n, "0");

  const bankNames = new Map<string, { en: string; he: string }>();
  const branches: ChildRow[] = [];
  for (const r of en) {
    const h = heById.get(r._id) ?? r;
    const bank = pad(r.Bank_Code, 2);
    if (!bankNames.has(bank)) bankNames.set(bank, { en: clean(r.Bank_Name), he: clean(h.Bank_Name) });
    const branch = pad(r.Branch_Code, 3);
    branches.push({
      code: `${bank}-${branch}`, en: clean(r.Branch_Name), he: clean(h.Branch_Name) || clean(r.Branch_Name), parentCode: bank,
      active: !clean(r.Close_Date),
      attrs: { branchCode: branch, address: clean(h.Branch_Address), city: clean(h.City) || title(clean(r.City)), phone: clean(r.Telephone) },
    });
  }
  for (const [code, n] of bankNames) {
    emit(
      `INSERT OR IGNORE INTO master_items (type_code, code, name_en, name_he, parent_id, sort_order, active, attributes, created_at) ` +
      `VALUES ('bank', ${q(code)}, ${q(n.en)}, ${q(n.he)}, NULL, 0, 1, '{}', ${q(now)});`,
    );
  }
  emit("");
  emitChildren("bank_branch", "bank", branches);
  log(`  ${bankNames.size} banks, ${branches.length} branches (${branches.filter((b) => b.active === false).length} closed, kept inactive)`);
}

await nationalities();
await geography();
await banks();
console.log(out.join("\n"));
